let container = document.getElementById("dailyWords");


if(container){

    container.innerHTML = "";

    const today = new Date();

const dayNumber = Math.floor(today.getTime() / 86400000);

const WORDS_PER_DAY = 6;

const startIndex = (dayNumber * WORDS_PER_DAY) % dailyWords.length;

container.innerHTML = "";

for(let i = 0; i < WORDS_PER_DAY; i++){

    let index = (startIndex + i) % dailyWords.length;

    let item = dailyWords[index];


    container.innerHTML += `

    <div class="daily-word-card">

        <div class="daily-unit">
            ${item.unit}
        </div>

        <h3>
            ${item.word}
        </h3>

        <p>
            ${item.meaning}
        </p>

        <button id="btn-${item.word}" onclick="learnWord('${item.word}')">

⭐ Learned

</button>

    </div>

    `;

}

}

function learnWord(word){

    let learnedWords =
    JSON.parse(localStorage.getItem("learnedWords")) || [];


    if(!learnedWords.includes(word)){

        learnedWords.push(word);

        localStorage.setItem(
            "learnedWords",
            JSON.stringify(learnedWords)
        );

    }


    let button =
    document.getElementById("btn-" + word);


    if(button){

        button.innerHTML = "✅ Öğrenildi";

        button.disabled = true;

    }

}